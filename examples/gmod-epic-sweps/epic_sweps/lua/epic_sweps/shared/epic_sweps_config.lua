--[[ Epic SWEPs - shared config. Both realms read this file; tweak here, not in the SWEPs. ]]

EpicSWEPs = EpicSWEPs or {}

local cfg = {}
cfg.Version = "1.0"

-- 100 ZOMBIE SPAWNER --------------------------------------------------------
cfg.ZombieSpawner = {
	ZombieCount = 100,			-- zombies per box. the name is a promise
	MaxZombiesAlive = 400,		-- hard safety cap, servers fall over long before this
	Waves = 4,					-- the horde arrives in this many waves (1 = all at once, it will hurt)
	WaveDelay = 0.45,			-- seconds between waves
	ZombieModelPool = "auto",	-- "auto" = the list below. drop in your own table of models to override
	Models = {
		"models/zombie_male.mdl",
		"models/zombie_player0.mdl",
		"models/zombie_player1.mdl",
		"models/zombie_05.mdl",
		"models/zombie_09.mdl",
		"models/barney.mdl",
		"models/elym.mdl"
	},
	HordeRadius = 620,			-- how wide the ring of corpses is
	RemoveAfter = 420,			-- clean our own zombies up after N seconds (0 = leave them)
	SpeedMultiplier = 1.1,		-- the horde walks faster than it should. that is the joke
	FallToFloor = true,			-- drop them a few feet so the arrival looks violent
	AllowNPCs = true,			-- spawn real zombie NPCs on NPC-capable gamemodes
	AllowRagdolls = true		-- on a plain sandbox server, fall back to physics ragdolls
}

-- 7 THOUSAND F*CKING MISSILES ----------------------------------------------
cfg.MissileBarrage = {
	MissileCount = 7000,		-- missiles that fall out of the sky. yes, all of them
	MaxMissilesDrawn = 2600,	-- streaks actually drawn per frame (the rest is rumour and noise)
	ImpactRadius = 1400,		-- size of the impact area
	ImpactSpreadTime = 2.6,		-- seconds the barrage rains for
	DamageMissilePercent = 7,	-- % of impacts that also spawn a real engine explosion (physics + noise)
	ExplosionCount = 44,		-- how many craters actually light up on screen per frame-window (7000 would be a white screen)
	Damage = {
		Enabled = true,
		PerMissile = 120,
		Radius = 165,
		DamageType = DMG_BULLET
	},
	-- how the streaks fall (client visuals only)
	Visuals = {
		LaunchHeight = 2600,	-- where they come out of the clouds
		FallTime = 0.9,			-- seconds from cloud to crater
		MinTail = 140,			-- world units of trail behind each missile
		MaxTail = 320,
		Width = 15				-- screen pixels at the tail end of the trail
	}
}

-- TIMING -------------------------------------------------------------------
-- The whole show, in seconds from the moment you click. Server and client read
-- the same numbers, so the voice, the text and the sky stay in step.
cfg.Seq = {
	Announce = 0,				-- title appears, first voice line
	Voice2 = 1.6,				-- second voice line ("blow up this man")
	Lock = 3.0,					-- target painted, siren, everything aims at the box
	Impacts = 3.35,				-- missiles start landing
	End = 8.5,					-- dust settles, entity cleans itself up
	RemoveDelay = 1.5		-- grace before the barrage entity goes away
}

